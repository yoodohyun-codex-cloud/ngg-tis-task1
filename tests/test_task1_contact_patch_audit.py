def contacts():
    return [(i, -24.5+i, .5, fraction*1e-6) for i, fraction in enumerate((1., .5, .01, .0005))]


def densities():
    # Inactive basis values intentionally dwarf the active values: a mistaken
    # patch-interleaved read produces a completely different answer.
    rows = {}
    for frequency, factor in zip(audit.FREQUENCIES, (1., 2., 3., 4.)):
        active = [complex(factor*k, 0) for k in range(1, 5)]
        inactive = [complex(1000+k, -400-k) for k in range(4)]
        rows[frequency] = active+inactive if frequency in (3000, 9000) else inactive+active
    return rows


def write_mask(path, rows=None):
    with Path(path).open('w') as stream:
        writer = csv.writer(stream)
        writer.writerow(['pad', 'i', 'j', 'area_m2'])
        for pad, x, y, area in rows or contacts():
            writer.writerow([pad, round(x+24.5), round(y+24.5), area])


def synthetic_case(root):
    run = root/'data-native/synthetic'
    ident = 'synthetic-concave-sc4'
    basis = run/'bases'/ident
    basis.mkdir(parents=True)
    post_dir = run/'postprocess'/ident
    post_dir.mkdir(parents=True)
    (run/'configs').mkdir()
    (run/'masks').mkdir()
    (run/'cases').mkdir()
    source = run/'frozen-source/tis-java/explore_tis.py'
    source.parent.mkdir(parents=True)
    source.write_text('WAVES = {"square_3h": (2., 1.)}\n')
    config = run/'configs/synthetic.properties'
    config.write_text('h_mm=1.\n'+''.join(f'z.{f}.re=1.\nz.{f}.im=.5\n' for f in audit.FREQUENCIES))
    mask = run/'masks/synthetic.csv'
    write_mask(mask)
    sha = audit.frozen.sha
    meta = dict(config_sha256=sha(config), channels=2, radius_mm=25, total_depth_mm=25.1,
        tissue_boundaries_mm=[0, .1, 5.1, 10.1, 25.1], cells=4, sc_cells=4,
        bulk_layer_counts=[14, 14, 40], h_xy_mm=1., source_peak_V=.5, source_resistance_ohm=50,
        phasor_convention='peak,+jomega_t', frequencies_Hz=list(audit.FREQUENCIES))
    (basis/'mesh-metadata.json').write_text(json.dumps(meta))
    (basis/'BASIS_COMPLETE').write_text('')
    (basis/'validation.json').write_text('{"status":"synthetic"}')
    for f, density in densities().items():
        with (basis/f'contacts-{f}.csv').open('w') as stream:
            writer = csv.writer(stream)
            writer.writerow(['pad', 'x_mm', 'y_mm', 'area_m2'])
            writer.writerows(contacts())
        (basis/f'density-{f}.bin').write_bytes(b''.join(struct.pack('<dd', v.real, v.imag) for v in density))
    native = {str(path):sha(path) for path in basis.iterdir()}
    native[str(config)] = sha(config)
    # Hand-calculated, not generated by the implementation under test.
    base_j = math.sqrt(22.5)
    metrics = dict(surface_J_RMS_max_A_m2=4*base_j, surface_J_RMS_p95_A_m2=2*base_j,
        contact_voltage_RMS_max_V=math.sqrt(1.25)*4*base_j, contact_power_W=22.5*3.098e-6)
    condition = dict(id=ident+'-square', waveform='square_3h', actual_fundamental_Hz=[3000, 3030],
        carrier_group=[0, 1], phase_deg=[0., 0.], source_Vpp_per_output=1., metrics=metrics)
    post = dict(id=ident, status='complete', mesh_metadata=meta, input_sha256=native,
        input_manifest_sha256=hashlib.sha256(json.dumps(native,sort_keys=True,separators=(',', ':')).encode()).hexdigest(),
        conditions=[condition])
    summary = post_dir/'summary.json'
    summary.write_text(json.dumps(post))
    case = dict(id=ident, config_file=str(config), config_sha256=sha(config), mask_file=str(mask), mask_sha256=sha(mask),
        circuit=dict(n_pads=4, n_outputs=2, return_topology='all_return_pads_ideal_common_GND'))
    registration = dict(source_commit='synthetic-test-only', cases=[case],
        source_and_input_sha256={str(root/'tis-java/explore_tis.py'):sha(source)})
    (run/'preregistration.json').write_text(json.dumps(registration))
    record = dict(id=ident, status='complete', postprocess_sha256=sha(summary),postprocess_path=str(summary),config_sha256=sha(config))
    (run/'cases'/(ident+'.json')).write_text(json.dumps(record))
    return summary


class PurePatchTests(unittest.TestCase):
    def test_pad_current_integrates_complex_patches_before_rms(self):
        rows = [(0, 0., 0., 1.), (0, 1., 0., 1.), (1, 2., 0., 1.),
            (2, 3., 0., 1.), (3, 4., 0., 1.)]
        # Pad0 has opposite patch currents at every frequency: finite patch J
        # and loss, exactly zero coherent physical-pad current.
        values = [1+0j, -1+0j, 2+0j, -1+0j, -1+0j]
        density = {f:values+[0j]*5 if f in (3000,9000) else [0j]*5+values for f in audit.FREQUENCIES}
        result = audit.reconstruct(rows, density, {f:1+0j for f in audit.FREQUENCIES}, [1., 1.])
        self.assertGreater(result['J_RMS_A_m2'][0], 0.)
        self.assertEqual(result['physical_pad_current_RMS_A'][0], 0.)
        self.assertEqual(result['physical_pad_current_RMS_A'][1], math.sqrt(8.))
        self.assertEqual(result['common_GND_return_current_RMS_A'], math.sqrt(8.))
        self.assertEqual(result['KCL_total_RMS_residual_A'], 0.)

    def test_pad_current_frequency_quadrature_and_all_four_ids_preserved(self):
        rows = [(i, float(i), 0., 1.) for i in range(4)]
        density, sources = {}, {}
        for index, frequency in enumerate(audit.FREQUENCIES):
            values = [1+0j, 2+0j, -1+0j, -2+0j] if index == 0 else (
                [3j, 4j, -3j, -4j] if index == 1 else [0j]*4)
            active = 0 if frequency in (3000,9000) else 1
            density[frequency] = values+[0j]*4 if active == 0 else [0j]*4+values
            matrix = [0j]*4
            matrix[active] = values[0]
            matrix[2+active] = values[1]
            sources[frequency] = matrix
        result = audit.reconstruct(rows, density, {f:1+0j for f in audit.FREQUENCIES}, [1., 1.], source_by_frequency=sources)
        expected = [math.sqrt(5.), math.sqrt(10.), math.sqrt(5.), math.sqrt(10.)]
        self.assertEqual(result['physical_pad_current_RMS_A'], expected)
        spectrum = result['physical_pad_current_spectrum']
        self.assertEqual(spectrum[0]['physical_pad_ids'], [0,1,2,3])
        self.assertEqual(spectrum[0]['imaginary_A_by_pad'], [-1.,-2.,1.,2.])
        self.assertEqual(spectrum[1]['real_A_by_pad'], [3.,4.,-3.,-4.])
        self.assertTrue(all(row['KCL_within_existing_native_diagnostic_limit'] for row in spectrum))
        self.assertTrue(all(row['source_output_comparison']['within_existing_native_diagnostic_limit'] for row in spectrum))

    def test_channel_major_actual_four_frequency_rms_not_patch_interleaved(self):
        rows = contacts()
        result = audit.reconstruct(rows, densities(), {f:1+.5j for f in audit.FREQUENCIES}, [2., 1.])
        for i in range(4):
            self.assertAlmostEqual(result['J_RMS_A_m2'][i], (i+1)*math.sqrt(22.5))
            self.assertAlmostEqual(result['contact_V_RMS_V'][i], (i+1)*math.sqrt(22.5*1.25))
        self.assertAlmostEqual(sum(result['contact_power_by_patch_W']), 22.5*3.098e-6)
        self.assertEqual([row['active_basis_channel'] for row in result['by_frequency']], [0, 1, 0, 1])

    def test_impedance_is_area_specific_scaled_exactly_once(self):
        result = audit.reconstruct(contacts(), densities(), {f:2+0j for f in audit.FREQUENCIES}, [2., 1.])
        self.assertAlmostEqual(sum(result['contact_power_by_patch_W']), 2*22.5*3.098e-6)
        self.assertAlmostEqual(result['contact_V_RMS_V'][-1], 2*4*math.sqrt(22.5))

    def test_fraction_bins_area_and_power_share_conserve_and_partial_face_hotspot(self):
        rows = contacts()
        electrical = audit.reconstruct(rows, densities(), {f:1+.5j for f in audit.FREQUENCIES}, [2., 1.])
        fractions = [row[3]/1e-6 for row in rows]
        result = audit.describe_patches(rows, fractions, electrical)
        bins = result['fraction_distribution']
        self.assertAlmostEqual(sum(row['area_share_of_all_contacts'] for row in bins), 1.)
        self.assertAlmostEqual(sum(row['power_share_of_all_contacts'] for row in bins), 1.)
        self.assertAlmostEqual(sum(row['contact_power_W'] for row in bins), result['contact_power_W'])
        self.assertEqual(result['Jmax_patch']['contact_to_full_XY_face_fraction'], .0005)
        self.assertEqual(result['top8_J_patches'][0]['pad'], 3)
        self.assertEqual(result['top8_V_patches'][0]['pad'], 3)
        self.assertEqual(len(result['pads']), 4)
        self.assertNotIn('edge_distance_mm', result['Jmax_patch'])

    def test_fixed_bin_boundary_point001_is_in_left_closed_second_bin(self):
        rows = contacts()
        electrical = audit.reconstruct(rows, densities(), {f:1+0j for f in audit.FREQUENCIES}, [2., 1.])
        result = audit.describe_patches(rows, [.001, .01, .1, 1.], electrical)
        self.assertEqual([b['patches'] for b in result['fraction_distribution']], [0, 1, 1, 1, 1])

    def test_frozen_nearest_sequential_cdf_includes_exact95percent(self):
        result = audit.generic_stats([1., 10.], [.95, .05], 'A/m2')
        self.assertEqual(result['p95'], 1.)
        self.assertIn('sequential', result['p95_definition'])

    def test_negative_nonfinite_impedance_and_wrong_density_shape_rejected(self):
        for impedance in (-1+1j, complex(math.nan, 0)):
            with self.subTest(impedance=impedance), self.assertRaises(ValueError):
                audit.reconstruct(contacts(), densities(), {f:impedance for f in audit.FREQUENCIES}, [2., 1.])
        bad = densities();bad[3000] = bad[3000][:-1]
        with self.assertRaises(ValueError):
            audit.reconstruct(contacts(), bad, {f:1+0j for f in audit.FREQUENCIES}, [2., 1.])

    def test_regression_tolerance_inclusive_and_no_relaxation(self):
        self.assertTrue(audit.metric_verification({'contact_power_W':1e-14}, {'contact_power_W':0.})['contact_power_W']['passed'])
        self.assertFalse(audit.metric_verification({'contact_power_W':math.nextafter(1e-14, math.inf)},
            {'contact_power_W':0.})['contact_power_W']['passed'])
        with self.assertRaises(ValueError):
            audit.metric_verification({'contact_power_W':math.inf}, {'contact_power_W':0.})

    def test_mask_native_xy_and_fraction_validation(self):
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp)/'mask.csv'
            write_mask(path)
            self.assertEqual(audit.validate_mask(contacts(), path, 1.), [1., .5, .01, .0005])
            changed = contacts();changed[-1] = (*changed[-1][:3], 1.01e-6)
            with self.assertRaises(ValueError):
                audit.validate_mask(changed, path, 1.)
            changed = contacts();changed[-1] = (3, -21.4, .5, .0005e-6)
            with self.assertRaises(ValueError):
                audit.validate_mask(changed, path, 1.)


class SyntheticSourceTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.root = Path(self.temp.name).resolve()
        self.contexts = [patch.object(module, 'ROOT', self.root) for module in (audit, audit.frozen, audit.view)]
        for context in self.contexts:context.start()
        self.summary = synthetic_case(self.root)
        self.source = self.root/'audit-synthetic.py';self.source.write_text('synthetic source only')
        self.impl_patch = patch.object(audit, 'implementation_source_paths', return_value=[self.source]);self.impl_patch.start()

    def tearDown(self):
        self.impl_patch.stop()
        for context in reversed(self.contexts):context.stop()
        self.temp.cleanup()

    def plan(self):
        return audit.make_preregistration([self.summary])

    def save_plan(self, plan):
        path = self.root/'contact-plan.json'
        path.write_text(json.dumps(plan))
        return path

    def test_metadata_builder_and_complete_small_array_readback(self):
        plan = self.plan()
        path = self.save_plan(plan)
        audit.verify_preregistration(path, [self.summary])
        result = audit.build_audit([self.summary], plan)
        self.assertEqual(result['new_PDE'], 0)
        self.assertFalse(result['full_E_phi_grid_NPZ_read'])
        row = result['cases'][0]
        self.assertEqual(row['mesh']['sc_cells'], 4)
        self.assertTrue(all(check['passed'] for check in row['summary_metric_verification'].values()))
        self.assertAlmostEqual(row['contact_power_W'], 69.705e-6)
        self.assertTrue(all('grid.csv' not in p and 'field-' not in p and 'potential-' not in p for p in result['input_sha256']))

    def test_optional_small_source_loss_matrices_use_native_average_power_factor(self):
        basis = self.summary.parents[2]/'bases/synthetic-concave-sc4'
        post = json.loads(self.summary.read_text())
        for frequency, factor in zip(audit.FREQUENCIES, (1., 2., 3., 4.)):
            channel = 0 if frequency in (3000, 9000) else 1
            contact_loss = .5*factor**2*3.098e-6
            source, loss = [0j]*4, [0j]*24
            source[3*channel] = complex(4*contact_loss, 0)
            loss[16+3*channel] = complex(contact_loss, 0)
            for name, values in (('source', source), ('loss', loss)):
                path = basis/f'{name}-{frequency}.bin'
                path.write_bytes(b''.join(struct.pack('<dd', v.real, v.imag) for v in values))
                post['input_sha256'][str(path)] = audit.frozen.sha(path)
        post['input_manifest_sha256'] = hashlib.sha256(json.dumps(post['input_sha256'],sort_keys=True,separators=(',', ':')).encode()).hexdigest()
        post['conditions'][0]['metrics']['source_power_W'] = 69.705e-6
        self.summary.write_text(json.dumps(post))
        receipt = self.summary.parents[2]/'cases/synthetic-concave-sc4.json'
        row = json.loads(receipt.read_text());row['postprocess_sha256'] = audit.frozen.sha(self.summary)
        receipt.write_text(json.dumps(row))
        plan = audit.make_preregistration([self.summary], include_circuit_matrices=True)
        result = audit.build_audit([self.summary], plan)
        checks = result['cases'][0]['optional_small_matrix_verification']
        self.assertTrue(checks['contact_power_W']['passed'])
        self.assertTrue(checks['source_power_W']['passed'])
        self.assertAlmostEqual(checks['source_power_W']['independent'], 69.705e-6)

    def test_preregistration_order_native_manifest_and_hash_tampering(self):
        plan = self.plan();path = self.save_plan(plan)
        with self.assertRaises(ValueError):
            audit.verify_preregistration(path, [self.root/'different-summary.json'])
        plan['cases'][0]['native_expected_input_sha256'] = {}
        path.write_text(json.dumps(plan))
        with self.assertRaises(ValueError):
            audit.verify_preregistration(path, [self.summary])
        plan = self.plan();path = self.save_plan(plan)
        self.source.write_text('changed')
        with self.assertRaises(ValueError):
            audit.verify_preregistration(path, [self.summary])

    def test_held_case_record_rejected_during_plan_build(self):
        record = self.summary.parents[2]/'cases/synthetic-concave-sc4.json'
        row = json.loads(record.read_text());row['status'] = 'error';record.write_text(json.dumps(row))
        with self.assertRaises(ValueError):
            self.plan()

    def test_large_and_forbidden_native_inputs_rejected_before_open(self):
        forbidden = self.root/'field-3000.bin';forbidden.write_text('must never read')
        with self.assertRaises(ValueError):audit.small_path(forbidden)
        archive = self.root/'volume.npz';archive.write_text('must never read')
        with self.assertRaises(ValueError):audit.small_path(archive)
        too_big = self.root/'density-3000.bin'
        with too_big.open('wb') as stream:stream.truncate(audit.MAX_FILE_BYTES+1)
        with self.assertRaises(ValueError):audit.small_path(too_big)

    def test_published_metric_mismatch_preserves_case_evidence(self):
        plan = self.plan()
        # Keep all source pins internally consistent, while creating a genuine
        # independently recomputed Jmax mismatch in a fake published result.
        post = json.loads(self.summary.read_text());post['conditions'][0]['metrics']['surface_J_RMS_max_A_m2'] *= 1.01
        self.summary.write_text(json.dumps(post))
        receipt = self.summary.parents[2]/'cases/synthetic-concave-sc4.json'
        record = json.loads(receipt.read_text());record['postprocess_sha256'] = audit.frozen.sha(self.summary)
        receipt.write_text(json.dumps(record))
        plan = self.plan()
        with self.assertRaises(audit.MetricMismatchError) as caught:
            audit.build_audit([self.summary], plan)
        self.assertFalse(caught.exception.evidence['summary_metric_verification']['surface_J_RMS_max_A_m2']['passed'])
        self.assertIn('fraction_distribution', caught.exception.evidence)


